#!/usr/bin/env python3
"""Generate the small pinned-app shell worker, never cache the ordinary workspace.
REUSE: shared single-app/services/Back/appearance/registry owners.
EXTEND: offline-sw's explicit navigation policy, not a second caching implementation.
"""
import argparse
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import re
from urllib.parse import urljoin, urlparse

ROOT = Path(__file__).resolve().parents[1] / 'web'
BASE = '/wizard-os-home/'

class Dependencies(HTMLParser):
    def __init__(self):
        super().__init__(); self.urls = []
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'script' and attrs.get('src'): self.urls.append(attrs['src'])
        if tag == 'link' and attrs.get('rel') == 'stylesheet': self.urls.append(attrs['href'])

def worker():
    shell = {'app-session.html', 'core/offline-sw.js'}
    html = Dependencies(); html.feed((ROOT / 'app-session.html').read_text())
    shell.update(html.urls)
    pending = list(shell)
    while pending:
        name = pending.pop(); path = ROOT / name
        if not path.is_file(): raise ValueError('Missing shell asset: ' + name)
        if path.suffix != '.css': continue
        for raw in re.findall(r'url\(\s*[\"\']?([^\s\)\"\']+)', path.read_text()):
            if raw.startswith(('data:', 'http:', 'https:', '#')): continue
            url = urlparse(urljoin(BASE + name, raw))
            if not url.path.startswith(BASE): raise ValueError('Out-of-scope shell asset: ' + raw)
            dep = url.path[len(BASE):]
            if dep not in shell: shell.add(dep); pending.append(dep)
    shell = sorted(shell)
    h = hashlib.sha256()
    for name in shell:
        h.update(name.encode()); h.update(b'\0'); h.update((ROOT / name).read_bytes())
    config = {'prefix': 'wizard-os-home-', 'version': h.hexdigest()[:20], 'shell': shell,
              'navigation': {'paths': [BASE, BASE + 'index.html'], 'parameter': 'app-session',
                             'apps': None, 'fallback': 'app-session.html'}}
    # The reviewed capability table is the sole opt-in source; do not duplicate its IDs here.
    return ('/* Generated by tools/build-offline-session.py. Never cache the workspace or private media. */\n'
            'importScripts("./core/offline-apps.js");\nself.WIZ_OFFLINE_CONFIG = ' +
            json.dumps(config, indent=2) + ';\n'
            'self.WIZ_OFFLINE_CONFIG.navigation.apps = self.WizOfflineApps.apps;\n'
            'importScripts("./core/offline-sw.js");\n')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    result = worker(); path = ROOT / 'sw.js'
    if args.check:
        if path.read_text() != result: raise SystemExit('Regenerate: python3 tools/build-offline-session.py')
        print('PASS pinned-shell dependency hash')
    else:
        path.write_text(result); print('Generated', path)
