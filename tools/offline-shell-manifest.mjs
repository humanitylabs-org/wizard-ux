// Generate/check the shell-only asset identity. No runtime/user data or media paths.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join,relative,extname } from 'node:path';
const root=fileURLToPath(new URL('../web/',import.meta.url));
const files=[];
async function walk(dir){for(const e of await readdir(dir,{withFileTypes:true})){const p=join(dir,e.name);if(e.isDirectory())await walk(p);else{const f=relative(root,p);if(f==='index.html'||(!['sw.js','core/offline-shell-manifest.js'].includes(f)&&['.js','.css','.woff2','.svg','.ico','.webmanifest'].includes(extname(f)))||/^(?:icons|brand)\/.*\.png$/.test(f))files.push(f);}}}
await walk(root);files.sort();const hash=createHash('sha256');
for(const f of files){hash.update(f+'\0');hash.update(await readFile(join(root,f)));hash.update('\0');}
const payload={version:hash.digest('hex').slice(0,20),shell:files.map(f=>f==='index.html'?'./':f)};
const output='// Generated by tools/offline-shell-manifest.mjs. Shell assets only.\nself.WIZ_SHELL_MANIFEST='+JSON.stringify(payload,null,2)+';\n';
const target=join(root,'core/offline-shell-manifest.js');
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==output)throw Error('Run node tools/offline-shell-manifest.mjs after changing shell assets');console.log('PASS offline shell identity '+payload.version+' ('+files.length+' assets)');}
else {await writeFile(target,output);console.log('Generated offline shell '+payload.version+' ('+files.length+' assets)');}
