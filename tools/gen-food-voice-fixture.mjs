// Writes the Food voice-table parity fixture the Android JVM test reads (AutomationShortcutsParityTest): the table web
// registers with native, and the action web's own matcher picks for each phrase. If native's java.util.regex picks the
// same, the floating orb / side button hear exactly what the in-app orb hears. tests/food-device.test.mjs fails when
// this file is stale. Usage: node tools/gen-food-voice-fixture.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

export const FIXTURE = new URL('../android/app/src/test/resources/food-voice-table.json', import.meta.url);

export function build() {
  const ctx = { window: {} };
  vm.runInNewContext(readFileSync(new URL('../web/food/rules.js', import.meta.url), 'utf8'), ctx);
  const R = ctx.window.WosFoodRules;
  const recipes = [['u0', 'Kra pao'], ['u1', 'Som tam & sticky rice'], ['u2', 'Morning coffee'], ['u3', 'Lunch'],
    ['u4', 'Kra pao moo saap + Thai iced tea'], ['u5', 'Pad thai (no peanuts)']].map(([id, name]) => ({ id, name }));
  const phrases = ['order my usual kra pao', 'order kra pao please', 'get me som tam', 'reorder my morning coffee', "what's a good kra pao place",
    'order a taxi to the airport', 'order my usual', 'order lunch', 'order food', 'order grab', 'get me something', 'i want something else',
    "i'd like to order dinner", 'order kra pao moo saap', 'order thai iced tea', 'order pad thai (no peanuts)', 'order pad thai', 'grab me something to eat',
    'order my usual kra pao moo saap', 'order something new now', 'order som tam & sticky rice again', 'food'];
  const table = R.voiceTable(recipes);
  return { note: 'Generated by tools/gen-food-voice-fixture.mjs from web/food/rules.js. Do not edit.', table,
    cases: phrases.map(p => ({ phrase: R.phrase(p), action: R.matchTable(table, p) })) };
}

if (import.meta.url === `file://${process.argv[1]}`) writeFileSync(FIXTURE, JSON.stringify(build(), null, 1) + '\n');
